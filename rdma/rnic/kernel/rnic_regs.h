#define AS02_CTL_REPLY_SLOT 0x90U
#define AS02_CTL_REPLY_KEY 0x94U
#define AS02_CTL_REPLY_ERROR 0x98U
#define AS02_CTL_REPLY_FLAGS 0x9cU
#define AS02_CTL_ENTRY_STATE 0xa0U
