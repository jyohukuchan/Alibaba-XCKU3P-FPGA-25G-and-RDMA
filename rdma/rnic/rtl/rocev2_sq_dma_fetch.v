// Synthesizable coherent-SQ fetch + actual Corundum descriptor/RAM/AXIS backend.
// Dedicated descriptor storage, NOT a payload-copy or an RDMA completion path.
// Caller supplies live coherent DMA64 ring mappings, real parent drain and
// downstream queue ownership. No allocator/AXI/verbs/board deployment implied.
`resetall
`timescale 1ns/1ps
`default_nettype none
module rocev2_sq_dma_fetch #(
    parameter MAX_QPS=8,
    parameter SEPARATE_RQ_ENABLE=0,
    parameter RECV_CANCEL_ENABLE=0,
    parameter RAM_SIZE=8192,
    parameter RAM_ADDR_WIDTH=15,
    parameter SEG_COUNT=2,
    parameter SEG_DATA_WIDTH=256,
    parameter SEG_BE_WIDTH=SEG_DATA_WIDTH/8,
    parameter SEG_ADDR_WIDTH=RAM_ADDR_WIDTH-$clog2(SEG_COUNT*SEG_BE_WIDTH),
    parameter RAM_SEL_WIDTH=1,
    parameter DMA_LEN_WIDTH=16,
    parameter TAG_WIDTH=16
)(
    input wire clk,
    input wire rst,
    input wire enable,
    // Direction is trusted management metadata, never a fetched opcode/QPN bit.
    input wire cfg_receive,
    input wire [1:0] admission_available,
    input wire [MAX_QPS-1:0] receive_downstream_guard,
    output wire [MAX_QPS-1:0] receive_queue_guard,
    output wire [MAX_QPS-1:0] receive_queue_active,
    output wire [MAX_QPS-1:0] receive_queue_pending,
    output wire [MAX_QPS-1:0] receive_queue_halted,
    output wire m_result_receive,
    input wire [1:0] cfg_command,
    input wire [23:0] cfg_qpn,
    input wire [15:0] cfg_pd,
    input wire [63:0] cfg_epoch,
    input wire [63:0] cfg_dma_base,
    input wire [3:0] cfg_log_depth,
    input wire [63:0] cfg_producer,
    input wire cfg_valid,
    output wire cfg_ready,
    output wire [7:0] cfg_response_error,
    output wire [23:0] cfg_response_qpn,
    output wire [63:0] cfg_response_epoch,
    output wire [63:0] cfg_response_consumer,
    output wire cfg_response_valid,
    input wire cfg_response_ready,
    input wire parent_dma_drained,
    input wire [MAX_QPS-1:0] downstream_queue_guard,
    output wire [MAX_QPS-1:0] queue_guard,
    output wire [MAX_QPS-1:0] queue_active,
    output wire [MAX_QPS-1:0] queue_pending,
    output wire [MAX_QPS-1:0] queue_halted,
    output wire [511:0] m_result_data,
    output wire [7:0] m_result_error,
    output wire [23:0] m_result_qpn,
    output wire [15:0] m_result_pd,
    output wire [63:0] m_result_epoch,
    output wire [63:0] m_result_sequence,
    output wire [15:0] m_result_tag,
    output wire m_result_valid,
    input wire m_result_ready,
    output wire busy,
    output wire tag_exhausted,
    output wire fault,
    output wire [7:0] fault_code,
    output wire [31:0] fetch_count,
    output wire [31:0] result_count,
    output wire [63:0] m_dma_read_address,
    output wire [RAM_SEL_WIDTH-1:0] m_dma_read_ram_sel,
    output wire [RAM_ADDR_WIDTH-1:0] m_dma_read_ram_address,
    output wire [DMA_LEN_WIDTH-1:0] m_dma_read_length,
    output wire [TAG_WIDTH-1:0] m_dma_read_tag,
    output wire m_dma_read_valid,
    input wire m_dma_read_ready,
    input wire [TAG_WIDTH-1:0] s_dma_read_status_tag,
    input wire [3:0] s_dma_read_status_error,
    input wire s_dma_read_status_valid,
    output wire [63:0] m_dma_write_address,
    output wire [RAM_SEL_WIDTH-1:0] m_dma_write_ram_sel,
    output wire [RAM_ADDR_WIDTH-1:0] m_dma_write_ram_address,
    output wire [31:0] m_dma_write_imm,
    output wire m_dma_write_imm_en,
    output wire [DMA_LEN_WIDTH-1:0] m_dma_write_length,
    output wire [TAG_WIDTH-1:0] m_dma_write_tag,
    output wire m_dma_write_valid,
    input wire m_dma_write_ready,
    input wire [TAG_WIDTH-1:0] s_dma_write_status_tag,
    input wire [3:0] s_dma_write_status_error,
    input wire s_dma_write_status_valid,
    input wire [SEG_COUNT*RAM_SEL_WIDTH-1:0] dma_ram_wr_cmd_sel,
    input wire [SEG_COUNT*SEG_BE_WIDTH-1:0] dma_ram_wr_cmd_be,
    input wire [SEG_COUNT*SEG_ADDR_WIDTH-1:0] dma_ram_wr_cmd_addr,
    input wire [SEG_COUNT*SEG_DATA_WIDTH-1:0] dma_ram_wr_cmd_data,
    input wire [SEG_COUNT-1:0] dma_ram_wr_cmd_valid,
    output wire [SEG_COUNT-1:0] dma_ram_wr_cmd_ready,
    output wire [SEG_COUNT-1:0] dma_ram_wr_done,
    input wire [SEG_COUNT*RAM_SEL_WIDTH-1:0] dma_ram_rd_cmd_sel,
    input wire [SEG_COUNT*SEG_ADDR_WIDTH-1:0] dma_ram_rd_cmd_addr,
    input wire [SEG_COUNT-1:0] dma_ram_rd_cmd_valid,
    output wire [SEG_COUNT-1:0] dma_ram_rd_cmd_ready,
    output wire [SEG_COUNT*SEG_DATA_WIDTH-1:0] dma_ram_rd_resp_data,
    output wire [SEG_COUNT-1:0] dma_ram_rd_resp_valid,
    input wire [SEG_COUNT-1:0] dma_ram_rd_resp_ready,
    output wire dma_drained,
    output wire [31:0] backend_command_count,
    output wire [31:0] backend_fence_count,
    output wire [31:0] backend_completion_count
);
wire [63:0] fetch_command_address;
wire [31:0] fetch_command_length;
wire [15:0] fetch_command_tag,status_tag;
wire fetch_command_valid,fetch_command_ready;
wire [511:0] read_data;
wire [63:0] read_keep;
wire read_last,read_valid,read_ready,status_valid,status_ready;
wire [7:0] status_error;
wire fetch_fault,fetch_busy,backend_fault,backend_idle,backend_dma_drained;
wire [7:0] fetch_fault_code,backend_fault_code;
wire [MAX_QPS-1:0] fetch_queue_guard,receive_fetch_guard;
assign fault=fetch_fault || backend_fault;
assign fault_code=fetch_fault ? fetch_fault_code : backend_fault ? (backend_fault_code|8'h80) : 8'd0;
assign busy=fetch_busy || !backend_idle || fault;
assign queue_guard=fetch_queue_guard | ({MAX_QPS{backend_fault}} & queue_active);
assign receive_queue_guard=receive_fetch_guard | ({MAX_QPS{backend_fault}} & receive_queue_active);
assign dma_drained=backend_dma_drained && backend_idle && !fetch_command_valid && !fault;
initial begin
    if(TAG_WIDTH!=16)$fatal(1,"SQ client requires exact16-bit app tags");
end
rocev2_sq_fetch #(.MAX_QPS(MAX_QPS),.SEPARATE_RQ_ENABLE(SEPARATE_RQ_ENABLE),.RECV_CANCEL_ENABLE(RECV_CANCEL_ENABLE)) fetch (
    .clk(clk),
    .rst(rst),
    .enable(enable && !backend_fault),
    .cfg_receive(cfg_receive),.admission_available(admission_available),
    .receive_downstream_guard(receive_downstream_guard),.receive_queue_guard(receive_fetch_guard),
    .receive_queue_active(receive_queue_active),.receive_queue_pending(receive_queue_pending),
    .receive_queue_halted(receive_queue_halted),.m_result_receive(m_result_receive),
    .cfg_command(cfg_command),
    .cfg_qpn(cfg_qpn),
    .cfg_pd(cfg_pd),
    .cfg_epoch(cfg_epoch),
    .cfg_dma_base(cfg_dma_base),
    .cfg_log_depth(cfg_log_depth),
    .cfg_producer(cfg_producer),
    .cfg_valid(cfg_valid),
    .cfg_ready(cfg_ready),
    .cfg_response_error(cfg_response_error),
    .cfg_response_qpn(cfg_response_qpn),
    .cfg_response_epoch(cfg_response_epoch),
    .cfg_response_consumer(cfg_response_consumer),
    .cfg_response_valid(cfg_response_valid),
    .cfg_response_ready(cfg_response_ready),
    .parent_dma_drained(parent_dma_drained && backend_dma_drained && backend_idle && !backend_fault),
    .downstream_queue_guard(downstream_queue_guard),
    .queue_guard(fetch_queue_guard),
    .queue_active(queue_active),
    .queue_pending(queue_pending),
    .queue_halted(queue_halted),
    .m_command_address(fetch_command_address),
    .m_command_length(fetch_command_length),
    .m_command_tag(fetch_command_tag),
    .m_command_valid(fetch_command_valid),
    .m_command_ready(fetch_command_ready),
    .s_axis_read_tdata(read_data),
    .s_axis_read_tkeep(read_keep),
    .s_axis_read_tlast(read_last),
    .s_axis_read_tvalid(read_valid),
    .s_axis_read_tready(read_ready),
    .s_status_tag(status_tag),
    .s_status_error(status_error),
    .s_status_valid(status_valid),
    .s_status_ready(status_ready),
    .m_result_data(m_result_data),
    .m_result_error(m_result_error),
    .m_result_qpn(m_result_qpn),
    .m_result_pd(m_result_pd),
    .m_result_epoch(m_result_epoch),
    .m_result_sequence(m_result_sequence),
    .m_result_tag(m_result_tag),
    .m_result_valid(m_result_valid),
    .m_result_ready(m_result_ready),
    .busy(fetch_busy),
    .tag_exhausted(tag_exhausted),
    .fault(fetch_fault),
    .fault_code(fetch_fault_code),
    .fetch_count(fetch_count),
    .result_count(result_count)
);
rocev2_corundum_dma_backend #(
    .RAM_SIZE(RAM_SIZE),.RAM_ADDR_WIDTH(RAM_ADDR_WIDTH),.SEG_COUNT(SEG_COUNT),
    .SEG_DATA_WIDTH(SEG_DATA_WIDTH),.SEG_BE_WIDTH(SEG_BE_WIDTH),.SEG_ADDR_WIDTH(SEG_ADDR_WIDTH),
    .RAM_SEL_WIDTH(RAM_SEL_WIDTH),.DMA_LEN_WIDTH(DMA_LEN_WIDTH),.TAG_WIDTH(TAG_WIDTH),
    .RECOVER_READ_DMA_ERROR(1)
) memory (
    .clk(clk),
    .rst(rst),
    .enable(1'b1),
    .parent_dma_drained(parent_dma_drained),
    .s_command_write(1'b0),
    .s_command_address(fetch_command_address),
    .s_command_length(fetch_command_length),
    .s_command_tag(fetch_command_tag),
    .s_command_valid(fetch_command_valid),
    .s_command_ready(fetch_command_ready),
    .s_axis_write_tdata(512'd0),
    .s_axis_write_tkeep(64'd0),
    .s_axis_write_tvalid(1'b0),
    .s_axis_write_tready(),
    .s_axis_write_tlast(1'b0),
    .m_axis_read_tdata(read_data),
    .m_axis_read_tkeep(read_keep),
    .m_axis_read_tvalid(read_valid),
    .m_axis_read_tready(read_ready),
    .m_axis_read_tlast(read_last),
    .m_status_tag(status_tag),
    .m_status_error(status_error),
    .m_status_valid(status_valid),
    .m_status_ready(status_ready),
    .m_dma_read_address(m_dma_read_address),
    .m_dma_read_ram_sel(m_dma_read_ram_sel),
    .m_dma_read_ram_address(m_dma_read_ram_address),
    .m_dma_read_length(m_dma_read_length),
    .m_dma_read_tag(m_dma_read_tag),
    .m_dma_read_valid(m_dma_read_valid),
    .m_dma_read_ready(m_dma_read_ready),
    .s_dma_read_status_tag(s_dma_read_status_tag),
    .s_dma_read_status_error(s_dma_read_status_error),
    .s_dma_read_status_valid(s_dma_read_status_valid),
    .m_dma_write_address(m_dma_write_address),
    .m_dma_write_ram_sel(m_dma_write_ram_sel),
    .m_dma_write_ram_address(m_dma_write_ram_address),
    .m_dma_write_imm(m_dma_write_imm),
    .m_dma_write_imm_en(m_dma_write_imm_en),
    .m_dma_write_length(m_dma_write_length),
    .m_dma_write_tag(m_dma_write_tag),
    .m_dma_write_valid(m_dma_write_valid),
    .m_dma_write_ready(m_dma_write_ready),
    .s_dma_write_status_tag(s_dma_write_status_tag),
    .s_dma_write_status_error(s_dma_write_status_error),
    .s_dma_write_status_valid(s_dma_write_status_valid),
    .dma_ram_wr_cmd_sel(dma_ram_wr_cmd_sel),
    .dma_ram_wr_cmd_be(dma_ram_wr_cmd_be),
    .dma_ram_wr_cmd_addr(dma_ram_wr_cmd_addr),
    .dma_ram_wr_cmd_data(dma_ram_wr_cmd_data),
    .dma_ram_wr_cmd_valid(dma_ram_wr_cmd_valid),
    .dma_ram_wr_cmd_ready(dma_ram_wr_cmd_ready),
    .dma_ram_wr_done(dma_ram_wr_done),
    .dma_ram_rd_cmd_sel(dma_ram_rd_cmd_sel),
    .dma_ram_rd_cmd_addr(dma_ram_rd_cmd_addr),
    .dma_ram_rd_cmd_valid(dma_ram_rd_cmd_valid),
    .dma_ram_rd_cmd_ready(dma_ram_rd_cmd_ready),
    .dma_ram_rd_resp_data(dma_ram_rd_resp_data),
    .dma_ram_rd_resp_valid(dma_ram_rd_resp_valid),
    .dma_ram_rd_resp_ready(dma_ram_rd_resp_ready),
    .idle(backend_idle),
    .dma_drained(backend_dma_drained),
    .fault(backend_fault),
    .fault_code(backend_fault_code),
    .command_count(backend_command_count),
    .fence_count(backend_fence_count),
    .completion_count(backend_completion_count)
);
endmodule
